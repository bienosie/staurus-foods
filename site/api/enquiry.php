<?php
declare(strict_types=1);
/*
 * Staurus Foods buyer enquiry endpoint.
 * Lightweight Release 1 PHP email transport. No database and no secrets in source.
 * SMTP relay/credentials can be introduced in CloudNext private configuration if
 * the hosting account cannot reliably deliver via PHP mail().
 */
header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');
header('X-Content-Type-Options: nosniff');

function reply(int $status, string $message): never {
    http_response_code($status);
    echo json_encode(['success' => $status === 200, 'message' => $message], JSON_UNESCAPED_SLASHES);
    exit;
}
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    header('Allow: POST');
    reply(405, 'This endpoint accepts enquiry submissions only.');
}
if (isset($_SERVER['CONTENT_LENGTH']) && (int)$_SERVER['CONTENT_LENGTH'] > 12000) {
    reply(413, 'The enquiry is too large.');
}
if (!str_starts_with((string)($_SERVER['CONTENT_TYPE'] ?? ''), 'application/x-www-form-urlencoded')) {
    reply(415, 'Unsupported submission type.');
}
$origin = (string)($_SERVER['HTTP_ORIGIN'] ?? '');
$allowed = ['https://staurusfoods.com', 'https://www.staurusfoods.com'];
if ($origin !== '' && !in_array($origin, $allowed, true)) {
    reply(403, 'Please submit this form from the Staurus Foods website.');
}
if ((string)($_POST['website'] ?? '') !== '') {
    reply(200, 'Thank you for your enquiry.');
}
if (isset($_POST['submitted_at']) && time() - (int)$_POST['submitted_at'] < 3) {
    reply(400, 'Please review the details and try again.');
}
$keys = ['name','company','email','destination','commodity','quantity','type','requirements'];
$values = [];
foreach ($keys as $key) {
    $v = trim((string)($_POST[$key] ?? ''));
    $v = preg_replace('/[\x00-\x1F\x7F]+/u', ' ', $v) ?? '';
    if (strlen($v) > ($key === 'requirements' ? 6000 : 500)) {
        reply(400, 'A field exceeds its permitted length.');
    }
    $values[$key] = $v;
}
foreach (['name','company','email','destination','commodity','quantity','requirements'] as $key) {
    if ($values[$key] === '') {
        reply(400, 'Please complete every required field.');
    }
}
if (!filter_var($values['email'], FILTER_VALIDATE_EMAIL)) {
    reply(400, 'Please enter a valid business email.');
}
if ((string)($_POST['privacy_confirmation'] ?? '') !== 'Accepted') {
    reply(400, 'Please confirm you have read the privacy notice.');
}
$permittedProducts = ['Dried hibiscus flowers', 'Raw cashew nuts', 'Cocoa beans', 'Sesame seeds', 'Soya beans', 'Other dry agricultural commodity'];
if (!in_array($values['commodity'], $permittedProducts, true)) {
    reply(400, 'Please choose a valid commodity.');
}

// Best-effort abuse throttling without collecting inquiry details in web-accessible storage.
// Requires private OS temporary directory with a writable filesystem.
$ip = (string)($_SERVER['REMOTE_ADDR'] ?? 'unknown');
$bucket = hash('sha256', $ip . '|staurus-foods-form-v1');
$limitFile = sys_get_temp_dir() . '/sf-form-' . $bucket;
$fp = @fopen($limitFile, 'c+');
if ($fp === false) {
    reply(503, 'Enquiry service is temporarily unavailable. Please email info@staurusfoods.com.');
}
try {
    if (!flock($fp, LOCK_EX)) {
        reply(503, 'Enquiry service is temporarily unavailable.');
    }
    $history = json_decode(stream_get_contents($fp) ?: '[]', true);
    $history = is_array($history) ? array_filter($history, fn($t) => is_int($t) && $t > time()-3600) : [];
    if (count($history) >= 4) {
        reply(429, 'Too many requests. Please try again later or email us directly.');
    }
    $history[] = time();
    rewind($fp); ftruncate($fp, 0);
    fwrite($fp, json_encode(array_values($history))); fflush($fp);
} finally {
    flock($fp, LOCK_UN); fclose($fp);
}
$labels = ['name'=>'Name', 'company'=>'Company', 'email'=>'Email', 'destination'=>'Destination', 'commodity'=>'Commodity', 'quantity'=>'Quantity', 'type'=>'Enquiry type', 'requirements'=>'Requirements'];
$lines = ["New buyer enquiry received through staurusfoods.com", ""];
foreach ($labels as $key=>$label) {
    $lines[] = $label . ': ' . $values[$key];
}
$lines[] = '';
$lines[] = 'This message was generated by the Staurus Foods enquiry form.';
$message = implode("\n", $lines);
$subject = 'Staurus Foods buyer enquiry: ' . $values['commodity'];
$headers = ['From: Staurus Foods Website <info@staurusfoods.com>', 'Reply-To: ' . $values['email'], 'Content-Type: text/plain; charset=UTF-8', 'X-Auto-Response-Suppress: All'];
$accepted = @mail('info@staurusfoods.com', $subject, $message, implode("\r\n", $headers));
if (!$accepted) {
    error_log('Staurus Foods enquiry transport rejected message');
    reply(503, 'We could not submit your enquiry. Please email info@staurusfoods.com directly.');
}
reply(200, 'Thank you. Your enquiry has been accepted for delivery. We will review it and respond by email.');
